/**
 * 将文本转为繁体字（根据高频古典字典）
 */
export function toTraditional(text: string): string {
  if (!text) return ''
  return text.split('').map(char => S2T_MAP[char] || char).join('')
}

/**
 * 标点符号正则（涵盖全角、半角常用标点）
 */
export const PUNCTUATION_REGEX = /[，。；：？！、,.!?;:："'“”‘’（）()《》〈〉·—…\-—\s]/g

/**
 * 古法去标点：去除所有全半角标点和多余空白
 */
export function stripPunctuation(text: string): string {
  if (!text) return ''
  return text.replace(PUNCTUATION_REGEX, '')
}

/**
 * 清理诗词正文：统一换行、去除 HTML 换行标签
 */
export function cleanVerseText(text?: string): string {
  if (!text) return ''
  return text
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n')
    .trim()
}

/**
 * 竖排分列拆分算法
 * @param content 诗词原文
 * @param removePunctuation 是否剔除标点
 * @param useTraditional 是否转为繁体
 */
export function splitVerseColumns(
  content: string,
  removePunctuation = false,
  useTraditional = false
): string[] {
  const cleaned = cleanVerseText(content)
  if (!cleaned) return []

  const rawLines = cleaned.split('\n').filter(line => line.trim().length > 0)
  const resultLines: string[] = []

  for (const line of rawLines) {
    let processed = line.trim()
    if (removePunctuation) {
      processed = stripPunctuation(processed)
    }
    if (useTraditional) {
      processed = toTraditional(processed)
    }
    if (processed) {
      // 若单行过长（如排律、歌行体未换行超过 14 字），智能拆为两列
      if (processed.length > 14) {
        let start = 0
        while (start < processed.length) {
          resultLines.push(processed.slice(start, start + 12))
          start += 12
        }
      } else {
        resultLines.push(processed)
      }
    }
  }

  return resultLines
}
